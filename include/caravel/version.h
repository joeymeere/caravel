#ifndef CARAVEL_VERSION_H
#define CARAVEL_VERSION_H

#define _CVL_STR(x)  #x
#define _CVL_XSTR(x) _CVL_STR(x)

#define CARAVEL_VERSION_MAJOR 0
#define CARAVEL_VERSION_MINOR 5
#define CARAVEL_VERSION_PATCH 1

#define CARAVEL_VERSION_STRING \
    _CVL_XSTR(CARAVEL_VERSION_MAJOR) \
    "." _CVL_XSTR(CARAVEL_VERSION_MINOR) "." _CVL_XSTR(CARAVEL_VERSION_PATCH)

#define CARAVEL_VERSION \
    (CARAVEL_VERSION_MAJOR * 10000 + CARAVEL_VERSION_MINOR * 100 + \
     CARAVEL_VERSION_PATCH)

#endif /* CARAVEL_VERSION_H */
